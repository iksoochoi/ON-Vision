def attach(methods):
    """Puts the explanations into the technique definitions (the older one-line help is replaced)."""
    for m in methods:
        m.pop("help", None)
        m["about"] = ABOUT[m["id"]]
        for p in m["params"]:
            p["hint"] = HINTS.get((m["id"], p["key"]), "")
